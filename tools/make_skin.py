def row(page, x0, x1, y, items):
    """items spread evenly over x0..x1: ("knob", key, label) / ("popup", key, label, w) / ("toggle", key, label) / ("readout", ...) / ("button", ...) / None"""
    n = len(items)
    cw = (x1 - x0) / n
    for i, it in enumerate(items):
        cx = int(x0 + cw * (i + 0.5))
        if it is None:
            continue
        if it[0] == "knob":
            page.knob(cx, y, it[1], it[2] if len(it) > 2 else None)
        elif it[0] == "popup":
            page.popup(cx, y, it[1], it[2], it[3] if len(it) > 3 else int(min(cw - 12, 170)), cw=it[4] if len(it) > 4 else None)
        elif it[0] == "toggle":
            page.toggle(cx, y, it[1], it[2])
        elif it[0] == "readout":
            page.readout(cx, y, it[1], it[2], it[3] if len(it) > 3 else int(cw - 20))
        elif it[0] == "button":
            page.button(cx, y, it[1], it[2])


