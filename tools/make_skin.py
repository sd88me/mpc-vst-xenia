class Page:
    def __init__(self, name, qkeys):
        self.name, self.qkeys = name, qkeys
        self.im = BG.copy()
        self.d = ImageDraw.Draw(self.im)
        self.widgets = []

    # ---- drawing
    def text(self, x, y, s, size=17, color=INK, style="Bold", anchor="la"):
        self.d.text((x, y), s, font=F(size, style), fill=color, anchor=anchor)

    def heading(self, x, y, w, title, left=False):
        """Xenia's section heading: blue italic title centred on a thin blue line (left: near the left end)"""
        f = F(22, "BoldItalic")
        tw = int(f.getlength(title))
        cx = x + 14 + 12 + tw // 2 if left else x + w // 2
        self.d.line((x, y + 14, cx - tw // 2 - 12, y + 14), fill=BLUE, width=2)
        self.d.line((cx + tw // 2 + 12, y + 14, x + w, y + 14), fill=BLUE, width=2)
        self.d.text((cx, y + 14), title, font=f, fill=BLUE, anchor="mm")

    def vline(self, x, y0, y1):
        self.d.line((x, y0, x, y1), fill=BLUE, width=2)

    def label(self, cx, y, s, color=INK, size=16):
        self.text(cx, y, s, size, color, "Bold", "ma")

    # ---- controls (a drawn label and the live widget over it)
    def knob(self, cx, cy, key, label=None):
        self.label(cx, cy - KNOB // 2 - 20, label or PARAMS[key]["name"])
        self.widgets.append('knob cx=%d cy=%d r=%d label="" key=%s ns=0 vs=22 vy=12 bw=%d' % (cx, cy + Y86, KNOB // 2 - 8, key, KNOB + 24))

    def popup(self, cx, cy, key, label, w=150, h=34, cw=None):
        self.label(cx, cy - h // 2 - 20, label, INK, 15)
        self.widgets.append('popup cx=%d cy=%d w=%d h=%d label="" key=%s%s' % (cx, cy + Y86, w, h, key, " cw=%d" % cw if cw else ""))

    def toggle(self, cx, cy, key, label):
        self.label(cx, cy - 36, label, INK, 15)
        self.widgets.append('toggle cx=%d cy=%d label="" key=%s ns=0' % (cx, cy + Y86, key))

    def readout(self, cx, cy, key, label, w=300, h=34):
        self.label(cx, cy - h // 2 - 20, label, INK, 15)
        self.widgets.append('readout cx=%d cy=%d w=%d h=%d label="" key=%s' % (cx, cy + Y86, w, h, key))

    def button(self, cx, cy, key, label):
        self.widgets.append('button cx=%d cy=%d label="%s" key=%s' % (cx, cy + Y86, label, key))

    def done(self):
        fn = "images/page_%s.png" % re.sub(r"[^A-Za-z0-9]+", "_", self.name)
        self.im.save(os.path.join(OUT, fn))
        emit("")
        emit("[tab %s]" % self.name)
        emit('art x=0 y=%d w=%d h=%d file="%s"' % (Y86, W, H, fn))
        lines.extend(self.widgets)
        emit('qlinks "%s" = %s' % (self.name, ",".join(self.qkeys)))


