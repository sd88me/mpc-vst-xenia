#!/usr/bin/env python3
"""params.lock + vst/params.json -> src/params_gen.h: the parameter table of the native front end (src/XeniaPlugin.cpp).

params.lock is the FROZEN VST order of the released 0.1.2 wrapper build (332 indices): the 253 keys of vst/params.json, then the
79 hidden "<key>__open" flags that build added, one per popup of vst/layout.conf. Saved projects and Q-Link assignments bind to these
indices. This build keeps them: index 253 is ui_open (0 = closed, k + 1 = the pick-list of the k-th popup in params.lock),
254..331 are inert reserved slots, and new parameters are only ever APPENDED (add them to APPENDED below and to params.lock).
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]
LOCK = [l.strip() for l in open(os.path.join(ROOT, "params.lock")) if l.strip()]
APPENDED = [                     # (key, name, min, max, default, flags) appended after the released 332, in this order
    ("fav_add", "+ Favourite", 0, 1, 0, 4096 | 1 | 512),       # kLocal | kMomentary | kNoAuto: store the current sound as a PRESET-list favourite
    ("fav_del", "- Favourite", 0, 1, 0, 4096 | 1 | 512),       # remove the current favourite
    ("random_patch", "Random Patch", 0, 1, 0, 4096 | 1 | 512), # make a new random sound in the edit buffer
]

keys = [p["key"] for p in P]
popups = [k[:-len("__open")] for k in LOCK[len(keys):len(keys) + 79]]
expect = keys + [k + "__open" for k in popups] + [a[0] for a in APPENDED]
if LOCK != expect:
    for i, (a, b) in enumerate(zip(LOCK, expect)):
        if a != b:
            sys.exit("params.lock index %d is %s, the table gives %s: the order is frozen (append only)" % (i, a, b))
    sys.exit("params.lock has %d entries, the table gives %d: the order is frozen (append only)" % (len(LOCK), len(expect)))
if not all(k in keys for k in popups):
    sys.exit("a popup in params.lock is not an engine key")
idx = {k: i for i, k in enumerate(keys)}

FL = dict(kMomentary=1, kText=2, kChoice=8, kUi=16, kReserved=32, kStep=128, kTile=256, kNoAuto=512, kPolled=1024,
          kRefresh=2048, kLocal=4096)
out = ["/* generated by tools/gen_sdk_params.py from params.lock + vst/params.json: do not edit. One row per parameter, frozen VST order. */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget; float stepDelta; };",
       ""]
rows = []


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


def row(key, name, lo, hi, d, fl, ch="nullptr", n=0, st=-1, sd=0.0):
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %s}," % (json.dumps(key), json.dumps(name), F(lo), F(hi), F(d), fl, ch, n, st, F(sd)))


for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n, st, sd = 0, "nullptr", 0, -1, 0.0
    if p.get("refresh_display"):
        fl |= FL["kRefresh"]
    if "options" in p:
        opts = p["options"]
        fl |= FL["kChoice"] | FL["kPolled"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        d = opts.index(p["default"]) if isinstance(p["default"], str) else p["default"]
        lo, hi = 0, len(opts) - 1
    else:
        lo, hi, d = p.get("min", 0), p.get("max", 1), p.get("default", 0)
        if k.startswith("bank_slot_") or k.startswith("patch_slot_"):
            fl |= FL["kMomentary"] | FL["kText"] | FL["kTile"] | FL["kNoAuto"]      # list tiles: tap = pick, lit = "<key>_on"
            lo, hi = 0, 1
        elif p.get("momentary"):
            fl |= FL["kMomentary"] | FL["kNoAuto"]
            lo, hi = 0, 1
            if p.get("step_of"):
                fl |= FL["kStep"]
                st, sd = idx[p["step_of"]], p.get("step_delta", 1)
        elif p.get("display") == "string":
            fl |= FL["kText"] | FL["kNoAuto"]                                        # readouts: the value is a change counter
            lo, hi, d = 0, 1023, 0
        else:
            fl |= FL["kPolled"]
    if k in ("bank_index", "preset"):
        fl |= FL["kNoAuto"]
    row(k, p["name"], lo, hi, d, fl, ch, n, st, sd)

row("ui_open", "Pick List", 0, len(popups), 0, FL["kUi"] | FL["kNoAuto"])
for j in range(1, len(popups)):
    row("rsv_%d" % (len(P) + j), "Reserved %d" % j, 0, 1, 0, FL["kReserved"] | FL["kNoAuto"])
for a in APPENDED:
    row(*a)

out += ["static const char *const g_popups[] = {%s};" % ", ".join(json.dumps(k) for k in popups)]
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % len(LOCK),
        "static const int kNumEngineParams = %d;   // 0 .. this - 1 are the engine's keys" % len(P),
        "static const int kUiParam = %d;            // ui_open: 0 closed, k + 1 = pick-list of g_popups[k]" % len(P),
        "static const int kNumPopups = %d;" % len(popups),
        "static const int kFavAdd = %d, kFavDel = %d, kRandom = %d, kFavSlots = 64;" % (len(keys) + 79, len(keys) + 80, len(keys) + 81), ""]
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out))
print("src/params_gen.h: %d params (%d engine, ui_open, %d reserved, %d appended)" % (len(LOCK), len(P), len(popups) - 1, len(APPENDED)))
